#!/usr/bin/env bash
set +e
set -u

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=dotfiles-link-common.sh
source "${SCRIPT_DIR}/dotfiles-link-common.sh"

SOURCE_DIR="${HOME}/.lark-channel"
TARGET_DIR="${SCRIPT_DIR}/dotfiles/.lark-channel"
LARK_CHANNEL_IGNORED_PATHS=(
  "logs/"
  "media/"
  "processes.json"
  "*.pid"
  "*.sock"
  "*.tmp"
  "tmp/"
  "cache/"
)

usage() {
  cat <<'EOF'
Usage:
  ./sync-lark-channel-config.sh backup   # Refuse raw export from a private local directory
  ./sync-lark-channel-config.sh restore  # Restore portable config when the snapshot is non-empty

Note:
  Automatic backup is disabled because this directory may contain credentials,
  workspace identifiers, message data, or other account-specific state.
EOF
}

rsync_lark_channel_config() {
  local source_dir="$1"
  local target_dir="$2"
  local rsync_args=()

  for ignored_path in "${LARK_CHANNEL_IGNORED_PATHS[@]}"; do
    rsync_args+=(--exclude "${ignored_path}")
  done

  rsync -a --delete \
    --delete-excluded \
    --exclude ".DS_Store" \
    --exclude ".git" \
    "${rsync_args[@]}" \
    "${source_dir}/" "${target_dir}/"
}

write_lark_channel_gitignore() {
  mkdir -p "${TARGET_DIR}"

  {
    echo "# Generated by sync-lark-channel-config.sh"
    echo "# Runtime state is machine-local and should not be committed."
    for ignored_path in "${LARK_CHANNEL_IGNORED_PATHS[@]}"; do
      echo "/${ignored_path}"
    done
  } >"${TARGET_DIR}/.gitignore"
}

backup_config() {
  write_lark_channel_gitignore
  echo "[lark-channel-sync] Automatic backup is disabled for a public repository."
  echo "[lark-channel-sync] Add only manually reviewed, non-sensitive files to ${TARGET_DIR}."
}

restore_config() {
  mkdir -p "${TARGET_DIR}"

  local portable_path
  portable_path="$(find "${TARGET_DIR}" -mindepth 1 -maxdepth 1 ! -name '.gitignore' ! -name '.DS_Store' -print -quit)"
  if [[ -z "${portable_path}" ]]; then
    write_lark_channel_gitignore
    echo "[lark-channel-sync] No portable config found; keeping ~/.lark-channel local."
    return 0
  fi

  if [[ -d "${SOURCE_DIR}" && ! -L "${SOURCE_DIR}" ]]; then
    if [[ -z "$(ls -A "${TARGET_DIR}" 2>/dev/null)" ]]; then
      echo "[lark-channel-sync] Migrating existing ~/.lark-channel into ${TARGET_DIR}..."
      rsync_lark_channel_config "${SOURCE_DIR}" "${TARGET_DIR}"
    fi
  fi

  write_lark_channel_gitignore
  ensure_symlink "${SOURCE_DIR}" "${TARGET_DIR}"
  echo "[lark-channel-sync] Linked ~/.lark-channel to ${TARGET_DIR}"
}

main() {
  if [[ $# -ne 1 ]]; then
    usage
    exit 1
  fi

  case "$1" in
    backup) backup_config ;;
    restore) restore_config ;;
    *)
      usage
      exit 1
      ;;
  esac
}

main "$@"
